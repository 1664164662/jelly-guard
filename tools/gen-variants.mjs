#!/usr/bin/env node
/**
 * 读取 variants/*.json，做结构校验，生成浏览器可直接加载的
 * src/generated-variants.js。没有任何第三方依赖。
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const VARIANTS_DIR = path.join(ROOT, 'variants');
const OUT_FILE = path.join(ROOT, 'src', 'generated-variants.js');
const ID_ORDER = ['mint', 'berry', 'sunset'];

const COLOR_KEYS = [
  'bg0', 'bg1', 'bg2', 'accent', 'accent2', 'enemy', 'enemy2',
  'text', 'muted', 'panel', 'panel2',
];

const LIMITS = {
  label: [2, 20],
  title: [2, 8],
  tagline: [4, 32],
  startCta: [2, 8],
  hint: [4, 24],
  winTitle: [2, 10],
  loseTitle: [2, 10],
  cta: [2, 8],
  sub: [4, 32],
};

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function charLength(value) {
  return Array.from(value).length;
}

export function validateVariant(raw, file = '') {
  const where = file ? ` (${path.basename(file)})` : '';
  assert(raw && typeof raw === 'object' && !Array.isArray(raw), `变体必须是对象${where}`);
  assert(/^[a-z][a-z0-9-]{1,23}$/.test(raw.id || ''), `id 不合法${where}`);
  assert(raw.source === 'handcrafted' || raw.source === 'ai-assisted', `source 不合法${where}`);

  assert(typeof raw.label === 'string', `缺少 label${where}`);
  for (const key of ['theme', 'copy', 'balance']) {
    assert(raw[key] && typeof raw[key] === 'object', `缺少 ${key}${where}`);
  }
  for (const key of COLOR_KEYS) {
    assert(/^#[0-9a-fA-F]{6}$/.test(raw.theme[key] || ''), `theme.${key} 必须是 6 位 hex${where}`);
  }
  for (const key of ['title', 'tagline', 'startCta', 'hint', 'winTitle', 'loseTitle', 'cta', 'sub']) {
    const value = raw.copy[key];
    const [min, max] = LIMITS[key];
    assert(typeof value === 'string', `copy.${key} 必须是字符串${where}`);
    const len = charLength(value.trim());
    assert(len >= min && len <= max, `copy.${key} 长度需在 ${min}-${max} 字之间${where}`);
  }
  assert(charLength(raw.label.trim()) >= LIMITS.label[0] && charLength(raw.label.trim()) <= LIMITS.label[1],
    `label 长度不合法${where}`);

  const { duration, baseHp, bossAt, sugarMax } = raw.balance;
  assert(Number.isInteger(duration) && duration >= 20 && duration <= 45, `duration 需在 20-45${where}`);
  assert(Number.isInteger(baseHp) && baseHp >= 2 && baseHp <= 5, `baseHp 需在 2-5${where}`);
  assert(Number.isInteger(bossAt) && bossAt > 10 && bossAt < duration, `bossAt 需在 10-duration 之间${where}`);
  assert(Number.isInteger(sugarMax) && sugarMax >= 60 && sugarMax <= 200, `sugarMax 需在 60-200${where}`);

  return {
    id: raw.id,
    label: raw.label.trim(),
    source: raw.source,
    theme: Object.fromEntries(COLOR_KEYS.map((key) => [key, raw.theme[key].toLowerCase()])),
    copy: {
      title: raw.copy.title.trim(),
      tagline: raw.copy.tagline.trim(),
      startCta: raw.copy.startCta.trim(),
      hint: raw.copy.hint.trim(),
      winTitle: raw.copy.winTitle.trim(),
      loseTitle: raw.copy.loseTitle.trim(),
      cta: raw.copy.cta.trim(),
      sub: raw.copy.sub.trim(),
    },
    balance: { duration, baseHp, bossAt, sugarMax },
  };
}

export async function loadVariants() {
  const entries = await fs.readdir(VARIANTS_DIR, { withFileTypes: true });
  const files = entries
    .filter((entry) => entry.isFile() && entry.name.endsWith('.json'))
    .map((entry) => path.join(VARIANTS_DIR, entry.name))
    .sort();

  const variants = [];
  const seen = new Set();
  for (const file of files) {
    let raw;
    try {
      raw = JSON.parse(await fs.readFile(file, 'utf8'));
    } catch (error) {
      throw new Error(`无法解析 ${path.basename(file)}: ${error.message}`);
    }
    const variant = validateVariant(raw, file);
    assert(!seen.has(variant.id), `id 重复: ${variant.id}`);
    seen.add(variant.id);
    variants.push(variant);
  }
  assert(variants.length > 0, 'variants/ 下没有可用 JSON');

  variants.sort((a, b) => {
    const ai = ID_ORDER.indexOf(a.id);
    const bi = ID_ORDER.indexOf(b.id);
    if (ai !== -1 || bi !== -1) return (ai === -1 ? 999 : ai) - (bi === -1 ? 999 : bi);
    return a.id.localeCompare(b.id);
  });
  return variants;
}

function serialize(variants) {
  const map = Object.fromEntries(variants.map((variant) => [variant.id, variant]));
  const payload = JSON.stringify(map, null, 2).replace(/</g, '\\u003c');
  return `/* AUTO-GENERATED by tools/gen-variants.mjs — 请修改 variants/*.json 后重新生成 */\n` +
    `window.JELLY_VARIANTS = ${payload};\n` +
    `window.JELLY_VARIANT_IDS = ${JSON.stringify(variants.map((variant) => variant.id))};\n`;
}

export async function generate({ quiet = false } = {}) {
  const variants = await loadVariants();
  await fs.mkdir(path.dirname(OUT_FILE), { recursive: true });
  await fs.writeFile(OUT_FILE, serialize(variants), 'utf8');
  if (!quiet) {
    console.log(`✓ 已生成 ${path.relative(ROOT, OUT_FILE)}`);
    variants.forEach((variant) => {
      console.log(`  · ${variant.id.padEnd(8)} ${variant.label.padEnd(8)} ${variant.source}`);
    });
  }
  return variants;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const checkOnly = process.argv.includes('--check');
  if (checkOnly) {
    const variants = await loadVariants();
    console.log(`✓ ${variants.length} 个变体通过校验`);
  } else {
    await generate();
  }
}
